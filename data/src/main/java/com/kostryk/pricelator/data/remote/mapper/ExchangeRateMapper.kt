package com.kostryk.pricelator.data.remote.mapper

import com.kostryk.pricelator.data.remote.model.ExchangeRateResponse
import com.kostryk.pricelator.domain.model.CurrencyEntity

object ExchangeRateMapper {

    fun mapToCurrencyEntities(response: ExchangeRateResponse): List<CurrencyEntity> {
        return response.conversionRates.map { (currencyCode, rate) ->
            CurrencyEntity(
                id = 0, // Auto-generated by Room
                name = getCurrencyName(currencyCode),
                symbol = currencyCode,
                exchangeRate = rate,
                isActive = true
            )
        }
    }

    private fun getCurrencyName(currencyCode: String): String {
        // Map of common currency codes to their full names
        return currencyNameMap[currencyCode] ?: currencyCode
    }

    private val currencyNameMap = mapOf(
        "USD" to "US Dollar",
        "EUR" to "Euro",
        "GBP" to "British Pound",
        "JPY" to "Japanese Yen",
        "CAD" to "Canadian Dollar",
